package com.arrow.acts.domain.models.enums;

/**
 * Habilidades o capacidades especiales de un miembro del equipo Arrow.
 * Un agente puede poseer múltiples capacidades simultáneamente.
 */
public enum Capability {

    /** Combate cuerpo a cuerpo de alto nivel. */
    HAND_TO_HAND_COMBAT,

    /** Uso de arco y flecha con precisión táctica. */
    ARCHERY,

    /** Hacking, intrusión de sistemas y soporte técnico remoto. */
    HACKING,

    /** Análisis de datos, inteligencia y planeación estratégica. */
    INTELLIGENCE_ANALYSIS,

    /** Infiltración y operaciones encubiertas. */
    STEALTH_OPERATIONS,

    /** Medicina de campo y atención de emergencias. */
    FIELD_MEDICINE,

    /** Pilotaje de vehículos y transporte táctico. */
    TACTICAL_DRIVING,

    /** Comunicaciones seguras y coordinación de campo. */
    COMMUNICATIONS
}
